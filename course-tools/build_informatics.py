def ceil_log2(n):
    i = 0
    while 2 ** i < n:
        i += 1
    return i


def truth_column(variables, f):
    """Столбец F по порядку двоичного счёта: 00…0, 00…1, …"""
    out = ''
    for bits in itertools.product([0, 1], repeat=len(variables)):
        out += '1' if f(**dict(zip(variables, bits))) else '0'
    return out


def imp(a, b):
    return (not a) or b


def bits_table(variables, f):
    """Markdown-таблица истинности (для разборов)."""
    head = '| ' + ' | '.join(variables) + ' | F |\n|' + '---|' * (len(variables) + 1) + '\n'
    rows = ''
    for bits in itertools.product([0, 1], repeat=len(variables)):
        v = 1 if f(**dict(zip(variables, bits))) else 0
        rows += '| ' + ' | '.join(map(str, bits)) + ' | ' + (f'<span class="hl-green">{v}</span>' if v else '0') + ' |\n'
    return head + rows


def task2(variables, f, value, rows, seed):
    """Задание 2: ищет фрагмент таблицы, по которому столбцы восстанавливаются однозначно.
    rows — сколько строк во фрагменте. Возвращает (фрагмент, ответ). Фрагмент: строки из 0/1/None."""
    rnd = random.Random(seed)
    n = len(variables)
    good = [bits for bits in itertools.product([0, 1], repeat=n) if bool(f(**dict(zip(variables, bits)))) == value]
    for _ in range(20000):
        perm = list(variables)
        rnd.shuffle(perm)              # perm[j] — переменная в столбце j
        chosen = rnd.sample(good, rows)
        # строка фрагмента в порядке столбцов
        frag = [[dict(zip(variables, bits))[perm[j]] for j in range(n)] for bits in chosen]
        blanks = rnd.randint(1, rows + 1)
        cells = [(r, c) for r in range(rows) for c in range(n)]
        for r, c in rnd.sample(cells, blanks):
            frag[r][c] = None
        if any(all(v is None for v in row) for row in frag):
            continue
        sols = solve_task2(variables, f, value, frag)
        if len(sols) == 1 and list(sols[0]) != sorted(variables):
            return frag, ''.join(sols[0])
    raise RuntimeError('не нашёлся однозначный фрагмент')


def solve_task2(variables, f, value, frag):
    n = len(variables)
    solutions = []
    for perm in itertools.permutations(variables):
        options_per_row = []
        for row in frag:
            opts = []
            free = [j for j in range(n) if row[j] is None]
            for fill in itertools.product([0, 1], repeat=len(free)):
                full = list(row)
                for j, v in zip(free, fill):
                    full[j] = v
                env = {perm[j]: full[j] for j in range(n)}
                if bool(f(**env)) == value:
                    opts.append(tuple(full))
            options_per_row.append(opts)
        # строки фрагмента не повторяются
        for choice in itertools.product(*options_per_row):
            if len(set(choice)) == len(choice):
                solutions.append(perm)
                FILLS[perm] = choice
                break
    return solutions


