def graph_svg(name, nodes, edges, directed=False, weights=None):
    """nodes — {буква: (x, y)}; edges — [(a, b)]. Картинка в стиле курса."""
    W = max(x for x, _ in nodes.values()) + 60
    H = max(y for _, y in nodes.values()) + 60
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
           f'font-family="Segoe UI, Arial, sans-serif">',
           f'<rect width="{W}" height="{H}" fill="#ffffff"/>',
           '<defs><marker id="a" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="8" markerHeight="8" '
           'orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 z" fill="#495057"/></marker></defs>']
    r = 18
    for a, b in edges:
        (x1, y1), (x2, y2) = nodes[a], nodes[b]
        dx, dy = x2 - x1, y2 - y1
        d = math.hypot(dx, dy)
        sx, sy = x1 + 30 + dx / d * r, y1 + 30 + dy / d * r
        ex, ey = x2 + 30 - dx / d * (r + (3 if directed else 0)), y2 + 30 - dy / d * (r + (3 if directed else 0))
        marker = ' marker-end="url(#a)"' if directed else ''
        out.append(f'<line x1="{sx:.1f}" y1="{sy:.1f}" x2="{ex:.1f}" y2="{ey:.1f}" stroke="#495057" '
                   f'stroke-width="2.2"{marker}/>')
        if weights and (a, b) in weights:
            mx, my = (x1 + x2) / 2 + 30 - dy / d * 12, (y1 + y2) / 2 + 34 + dx / d * 12
            out.append(f'<text x="{mx:.1f}" y="{my:.1f}" font-size="14" text-anchor="middle" fill="#c92a2a" '
                       f'font-weight="bold">{weights[(a, b)]}</text>')
    for v, (x, y) in nodes.items():
        out.append(f'<circle cx="{x + 30}" cy="{y + 30}" r="{r}" fill="#ffffff" stroke="#1d3557" stroke-width="2.2"/>')
        out.append(f'<text x="{x + 30}" y="{y + 36}" font-size="16" font-weight="bold" text-anchor="middle" '
                   f'fill="#1d3557">{v}</text>')
    out.append('</svg>')
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    (IMG_DIR / name).write_text('\n'.join(out) + '\n', encoding='utf-8')
    return f'images/{name}'


