def add(les, id_, type_, title, statement, answer, solution, hint='', **extra):
    answers = answer if isinstance(answer, list) else [answer]
    t = {'id': id_, 'type': type_, 'title': title, 'statement': statement.strip(),
         'answers': [str(a) for a in answers], 'solution': solution.strip()}
    if hint:
        t['hint'] = hint
    t.update(extra)
    les['tasks'].append(t)


def answer_task(les, id_, title, statement, answer, solution, hint=''):
    add(les, id_, 'ANSWER', title, statement, answer, solution, hint)


