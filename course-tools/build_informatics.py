def frag_table(frag, value, n):
    head = '| ' + ' | '.join(['?'] * n) + ' | F |\n|' + '---|' * (n + 1) + '\n'
    body = ''
    for row in frag:
        body += '| ' + ' | '.join('' if v is None else str(v) for v in row) + f' | {int(value)} |\n'
    return head + body


def filled_table(frag, filled, letters, value):
    head = '| ' + ' | '.join(letters) + ' | F |\n|' + '---|' * (len(letters) + 1) + '\n'
    body = ''
    for row, full in zip(frag, filled):
        cells = [str(v) if row[j] is not None else f'<span class="hl-yellow">{v}</span>' for j, v in enumerate(full)]
        body += '| ' + ' | '.join(cells) + f' | {int(value)} |\n'
    return head + body


def segments_answer(P, Q, f, goal):
    """Наименьшая/наибольшая длина отрезка A с концами в концах P и Q, при которой f истинна для всех x."""
    points = sorted({P[0], P[1], Q[0], Q[1]})
    lo, hi = points[0] - 10, points[-1] + 10
    xs = [lo + k * 0.25 for k in range(int((hi - lo) / 0.25) + 1)]
    best = None
    for a in points:
        for b in points:
            if b < a:
                continue
            if all(f(P[0] <= x <= P[1], Q[0] <= x <= Q[1], a <= x <= b) for x in xs):
                length = b - a
                if best is None or (length < best if goal == 'min' else length > best):
                    best = length
    return best


def div_answer(f, goal, a_max=1000, x_max=3000):
    found = [A for A in range(1, a_max + 1) if all(f(x, A) for x in range(1, x_max + 1))]
    return min(found) if goal == 'min' else max(found)


def fano_ok(codes):
    return all(not b.startswith(a) for a in codes for b in codes if a != b) and len(set(codes)) == len(codes)


def fano_free_nodes(codes, depth=8):
    """Корни свободных поддеревьев: на пути к ним нет кода и под ними нет кода."""
    result = []

    def walk(prefix):
        if any(c == prefix for c in codes):
            return
        if not any(c.startswith(prefix) for c in codes):
            result.append(prefix)
            return
        if len(prefix) < depth:
            walk(prefix + '0')
            walk(prefix + '1')
    walk('')
    return result


def fano_min_sum(codes, extra):
    """Наименьшая сумма длин extra новых кодов, чтобы код остался префиксным."""
    g = {1: 0}
    for m in range(2, extra + 1):
        g[m] = min(g[a] + g[m - a] for a in range(1, m)) + m

    def cost(depth, m):
        return 0 if m == 0 else m * depth + g[m]
    roots = fano_free_nodes(codes)
    INF = 10 ** 9
    best = [(0, [])] + [(INF, None)] * extra      # (сумма, сколько кодов в каждый корень)
    for root in roots:
        nxt = [(INF, None)] * (extra + 1)
        for used in range(extra + 1):
            if best[used][0] == INF:
                continue
            for m in range(extra - used + 1):
                c = best[used][0] + cost(len(root), m)
                if c < nxt[used + m][0]:
                    nxt[used + m] = (c, best[used][1] + [m])
        best = nxt
    total, split = best[extra]

    def build(prefix, m):
        if m == 0:
            return []
        if m == 1:
            return [prefix]
        a = min(range(1, m), key=lambda k: (g[k] + g[m - k], -k))
        return build(prefix + '0', a) + build(prefix + '1', m - a)
    new_codes = [c for root, m in zip(roots, split) for c in build(root, m)]
    assert sum(map(len, new_codes)) == total and fano_ok(codes + new_codes)
    return total, new_codes


def count_paths(edges, start, end, via=None, avoid=None):
    out = {}
    for a, b in edges:
        out.setdefault(a, []).append(b)

    def paths(a, b, banned):
        if a == b:
            return 1
        return sum(paths(n, b, banned) for n in out.get(a, []) if n not in banned)
    banned = set(avoid or '')
    if via:
        return paths(start, via, banned) * paths(via, end, banned)
    return paths(start, end, banned)


def graph_matchings(letters, edges, numbers, table_edges):
    """Все биекции буква → номер, при которых дороги графа совпадают с дорогами таблицы."""
    E = {frozenset(e) for e in edges}
    T = {frozenset(e) for e in table_edges}
    found = []
    for perm in itertools.permutations(range(1, numbers + 1), len(letters)):
        m = dict(zip(letters, perm))
        if {frozenset((m[a], m[b])) for a, b in E} == T:
            found.append(m)
    return found


def adjacency_md(numbers, weights):
    """Таблица с номерами пунктов; weights — {(i, j): длина}."""
    head = '| | ' + ' | '.join(f'П{i}' for i in range(1, numbers + 1)) + ' |\n|' + '---|' * (numbers + 1) + '\n'
    body = ''
    for i in range(1, numbers + 1):
        cells = []
        for j in range(1, numbers + 1):
            w = weights.get((i, j)) or weights.get((j, i))
            cells.append(str(w) if w else '')
        body += f'| **П{i}** | ' + ' | '.join(cells) + ' |\n'
    return head + body


def ip_bytes(text):
    return [int(p) for p in text.split('.')]


def mask_from_prefix(k):
    bits = '1' * k + '0' * (32 - k)
    return [int(bits[i:i + 8], 2) for i in range(0, 32, 8)]


